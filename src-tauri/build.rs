use std::{env, fs, path::PathBuf};

const PNG_1X1_RGBA: &[u8] = &[
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4,
    0x89, 0x00, 0x00, 0x00, 0x0b, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x60, 0x00, 0x02, 0x00,
    0x00, 0x05, 0x00, 0x01, 0x7a, 0x5e, 0xab, 0x3f, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44,
    0xae, 0x42, 0x60, 0x82,
];

fn ensure_build_icons() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let icons_dir = manifest_dir.join("icons");
    fs::create_dir_all(&icons_dir).expect("create icons directory");

    let png_path = icons_dir.join("icon.png");
    if !png_path.exists() {
        fs::write(&png_path, PNG_1X1_RGBA).expect("write PNG build icon");
    }

    let ico_path = icons_dir.join("icon.ico");
    if !ico_path.exists() {
        let mut ico = Vec::with_capacity(22 + PNG_1X1_RGBA.len());
        ico.extend_from_slice(&[0x00, 0x00, 0x01, 0x00, 0x01, 0x00]);
        ico.extend_from_slice(&[0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00]);
        ico.extend_from_slice(&(PNG_1X1_RGBA.len() as u32).to_le_bytes());
        ico.extend_from_slice(&22_u32.to_le_bytes());
        ico.extend_from_slice(PNG_1X1_RGBA);
        fs::write(ico_path, ico).expect("write ICO build icon");
    }
}

fn main() {
    ensure_build_icons();
    tauri_build::build()
}
