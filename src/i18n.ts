const dictionaries = { en, "zh-CN": zhCN } as const;

export type TranslationKey = keyof typeof en;
export type Translator = (key: TranslationKey, values?: TranslationValues) => string;

export function resolveLocale(
  preference: LanguagePreference,
  systemLocale = typeof navigator === "undefined" ? "en-US" : navigator.language,
): ResolvedLocale {
  if (preference === "en") {
    return { language: "en", formatLocale: "en-US" };
  }
  if (preference === "zh-CN") {
    return { language: "zh-CN", formatLocale: "zh-CN" };
  }

  const normalized = systemLocale.replace(/_/g, "-");
  if (/^zh(?:-(?:cn|sg|hans)(?:-|$)|$)/i.test(normalized)) {
    return { language: "zh-CN", formatLocale: normalized };
  }
  if (/^en(?:-|$)/i.test(normalized)) {
    return { language: "en", formatLocale: normalized };
  }
  return { language: "en", formatLocale: "en-US" };
}

export function readLanguagePreference(): LanguagePreference {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_PREFERENCE_KEY);
    return saved === "en" || saved === "zh-CN" || saved === "system" ? saved : "system";
  } catch {
    return "system";
  }
}

export function saveLanguagePreference(preference: LanguagePreference) {
  try {
    window.localStorage.setItem(LANGUAGE_PREFERENCE_KEY, preference);
  } catch {
    // The application remains usable when WebView storage is unavailable.
  }
}

export function createTranslator(language: AppLanguage): Translator {
  return (key, values = {}) =>
    dictionaries[language][key].replace(/\{(\w+)\}/g, (match, name: string) =>
      name in values ? String(values[name]) : match,
    );
}

export function formatNumber(value: number, formatLocale: string) {
  return new Intl.NumberFormat(formatLocale).format(value);
}

export function formatPercent(value: number, formatLocale: string) {
  return new Intl.NumberFormat(formatLocale, {
    style: "percent",
    maximumFractionDigits: 0,
  }).format(value / 100);
}

export function formatDateTime(timestamp: number, formatLocale: string) {
  return new Intl.DateTimeFormat(formatLocale, {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(timestamp * 1000));
}

export function formatRelativeTime(timestamp: number, formatLocale: string, nowMs = Date.now()) {
  const seconds = Math.round((timestamp * 1000 - nowMs) / 1000);
  const units: Array<[Intl.RelativeTimeFormatUnit, number]> = [
    ["day", 86_400],
    ["hour", 3_600],
    ["minute", 60],
    ["second", 1],
  ];
  const [unit, divisor] = units.find(([, divisor]) => Math.abs(seconds) >= divisor) || units[units.length - 1]!;
  return new Intl.RelativeTimeFormat(formatLocale, { numeric: "auto" }).format(
    Math.round(seconds / divisor),
    unit,
  );
}

export function formatQuotaResetTime(timestamp: number, formatLocale: string, nowMs = Date.now()) {
  const target = new Date(timestamp * 1000);
  const remainingMinutes = Math.ceil((target.getTime() - nowMs) / 60_000);
  if (remainingMinutes <= 0) return formatLocale.startsWith("zh") ? "待刷新" : "Refresh to update";
  const days = Math.floor(remainingMinutes / 1_440);
  const hours = Math.floor((remainingMinutes % 1_440) / 60);
  const minutes = remainingMinutes % 60;
  const chinese = formatLocale.startsWith("zh");
  const relative = days
    ? chinese ? `${days}天${hours ? `${hours}小时` : ""}` : `${days}d${hours ? ` ${hours}h` : ""}`
    : hours
      ? chinese ? `${hours}小时${minutes ? `${minutes}分` : ""}` : `${hours}h${minutes ? ` ${minutes}m` : ""}`
      : chinese ? `${minutes}分` : `${minutes}m`;
  const two = (value: number) => String(value).padStart(2, "0");
  const year = target.getFullYear() === new Date(nowMs).getFullYear() ? "" : `${target.getFullYear()}/`;
  return `${relative} · ${year}${two(target.getMonth() + 1)}/${two(target.getDate())} ${two(target.getHours())}:${two(target.getMinutes())}`;
}

export function formatDateTimeWithRelative(
  timestamp: number,
  formatLocale: string,
  nowMs = Date.now(),
) {
  return `${formatDateTime(timestamp, formatLocale)} (${formatRelativeTime(timestamp, formatLocale, nowMs)})`;
}

export function formatCompactExpiry(timestamp: number, formatLocale: string, nowMs = Date.now()) {
  const target = new Date(timestamp * 1000);
  const remainingMinutes = Math.ceil((target.getTime() - nowMs) / 60_000);
  if (remainingMinutes <= 0) return formatLocale.startsWith("zh") ? "已到期" : "Expired";
  const days = Math.floor(remainingMinutes / 1_440);
  const hours = Math.floor((remainingMinutes % 1_440) / 60);
  const minutes = remainingMinutes % 60;
  const relative = formatLocale.startsWith("zh")
    ? `${days ? `${days}天` : ""}${hours ? `${hours}小时` : ""}${!days && !hours ? `${minutes}分钟` : ""}后`
    : `in ${days ? `${days}d ` : ""}${hours ? `${hours}h` : ""}${!days && !hours ? `${minutes}m` : ""}`.trim();
  const two = (value: number) => String(value).padStart(2, "0");
  const year = target.getFullYear() === new Date(nowMs).getFullYear() ? "" : `${target.getFullYear()}/`;
  return `${relative} · ${year}${two(target.getMonth() + 1)}/${two(target.getDate())} ${two(target.getHours())}:${two(target.getMinutes())}`;
}
